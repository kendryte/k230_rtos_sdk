#!/usr/bin/env python3
"""Select an SDK output, maintain compatibility links, and run make under a lock."""

import argparse
from contextlib import contextmanager
import fcntl
import os
from pathlib import Path
import re
import shlex
import shutil
import subprocess
import sys
import tempfile


STATE_PATHS = (".config", ".config.old", "include")
INSPECT_GOALS = {"help", "list-def", "list_def"}
CONFIG_GOALS = INSPECT_GOALS | {"menuconfig", "savedefconfig", "outputmakefile",
                                "sdk-kconfig", "dl_toolchain", "rm_image", "flash"}


def config_name(config):
    if not config.is_file():
        return None
    match = re.search(r'^CONFIG_BOARD_CONFIG_NAME="([\w.-]+)"$',
                      config.read_text(), re.MULTILINE)
    if not match or not match[1].endswith("_defconfig"):
        raise ValueError("Missing or invalid CONFIG_BOARD_CONFIG_NAME in {}".format(config))
    return match[1]


def link_state(root, output):
    for name in STATE_PATHS:
        link = root / name
        target = os.path.relpath(output / name, root)
        if link.is_symlink() and os.readlink(link) == target:
            continue
        if link.exists() and not link.is_symlink():
            raise ValueError("Refusing to replace unmigrated {}".format(link))
        temporary = root / (name.replace("/", "_") + ".link.{}".format(os.getpid()))
        try:
            temporary.symlink_to(target)
            temporary.replace(link)
        finally:
            temporary.unlink(missing_ok=True)


def migrate_legacy(root):
    """Move the current legacy state without changing file contents or mtimes."""
    config = root / ".config"
    if config.is_symlink() or not config.exists():
        return
    output = root / "output" / config_name(config)
    sources = [root / name for name in STATE_PATHS
               if (root / name).exists() and not (root / name).is_symlink()]
    for source in sources:
        destination = output / source.name
        if destination.exists() or destination.is_symlink():
            raise ValueError("Cannot migrate {}: {} already exists".format(source, destination))
    output.mkdir(parents=True, exist_ok=True)
    write_makefile(root, output)
    for source in sources:
        source.rename(output / source.name)
    (output / "include").mkdir(exist_ok=True)
    link_state(root, output)


def write_makefile(root, output):
    # Outputs live directly below output/, so this continues working if the
    # entire checkout is moved. Use the Makefile's path, also for `make -f`.
    content = """# Generated by the SDK; configuration and build artifacts live here.
SDK_DISPATCH_OUTPUT := $(abspath $(dir $(lastword $(MAKEFILE_LIST))))
SDK_SRC_ROOT_DIR := $(abspath $(SDK_DISPATCH_OUTPUT)/../..)
include $(SDK_SRC_ROOT_DIR)/tools/output.mk
"""
    path = output / "Makefile"
    if path.exists() and path.read_text() == content:
        return
    if path.exists() and not path.read_text().startswith("# Generated by the SDK;"):
        raise ValueError("Refusing to overwrite {}".format(path))
    path.write_text(content)


def resolve_output(root, requested, goals):
    """Determine the output without changing the checkout."""
    defconfigs = [goal for goal in goals if goal.endswith("_defconfig")]
    if len(defconfigs) > 1:
        raise ValueError("Select only one defconfig per make invocation")
    name = defconfigs[0] if defconfigs else None
    if name and (Path(name).name != name or not (root / "configs" / name).is_file()):
        raise ValueError("Unknown defconfig: {}".format(name))
    # Configuration must be loaded again after applying a defconfig.
    if name and len(goals) != 1:
        raise ValueError("Run make {} first, then run make for build targets".format(name))

    output = Path(requested).resolve() if requested else None
    if output and output.parent != root / "output":
        raise ValueError("Select a directory directly under {}/output".format(root))
    if name:
        destination = root / "output" / name
        if output and output != destination:
            raise ValueError("Run make {} from the SDK root to select another output".format(name))
        output = destination
    legacy = root / ".config"
    legacy_output = (root / "output" / config_name(legacy)
                     if legacy.is_file() and not legacy.is_symlink() else None)
    if output and not name and not (output / ".config").is_file() and output != legacy_output:
        raise ValueError("No saved configuration in {}; run make {} from the SDK root first".
                         format(output, output.name))

    current = (root / ".config").resolve().parent if (root / ".config").is_symlink() else None
    output = output or current or legacy_output
    if output is None:
        return None
    if output.parent != root / "output":
        raise ValueError("The active .config must point inside {}/output/<defconfig>".format(root))
    return output


def activate_output(root, output):
    current = (root / ".config").resolve().parent if (root / ".config").is_symlink() else None
    link_state(root, output)
    if current != output:
        # The RT-Smart BSP still generates configuration in its source tree.
        # Reconfigure it on the next build after a switch; keep object caches.
        (root / "src/rtsmart/.parse_config").unlink(missing_ok=True)


def make_inspection_mode():
    # GNU make encodes single-letter flags in the first MAKEFLAGS word.
    words = shlex.split(os.environ.get("MAKEFLAGS", ""))
    short = words[0] if words and not words[0].startswith("-") and "=" not in words[0] else ""
    if "q" in short or "--question" in words:
        return "question"
    if "n" in short or any(flag in words for flag in ("--dry-run", "--just-print", "--recon")):
        return "dry-run"
    return None


def needs_sync(goals):
    return not goals or any(goal not in CONFIG_GOALS and not goal.endswith(
        ("_defconfig", "clean")) for goal in goals)


def remove_state(path):
    if path.is_dir() and not path.is_symlink():
        shutil.rmtree(path)
    else:
        path.unlink(missing_ok=True)


@contextmanager
def config_transaction(output):
    """Restore saved configuration, including mtimes, if any config step fails."""
    with tempfile.TemporaryDirectory(prefix=".config-backup-", dir=output.parent) as temporary:
        backup = Path(temporary)
        for name in STATE_PATHS:
            source = output / name
            if source.is_dir() and not source.is_symlink():
                shutil.copytree(source, backup / name, symlinks=True)
            elif source.exists() or source.is_symlink():
                shutil.copy2(source, backup / name, follow_symlinks=False)
        committed = []
        try:
            yield lambda: committed.append(True)
        finally:
            if not committed:
                for name in STATE_PATHS:
                    remove_state(output / name)
                    saved = backup / name
                    if saved.exists() or saved.is_symlink():
                        saved.rename(output / name)


def build_subprocess_fds():
    """Descriptors Python callers must preserve when starting a nested make."""
    descriptors = []
    lock_fd = os.environ.get("SDK_BUILD_LOCK_FD")
    if lock_fd:
        descriptors.append(int(lock_fd))
    jobserver = re.search(r"--jobserver-(?:auth|fds)=(\d+),(\d+)", os.environ.get("MAKEFLAGS", ""))
    if jobserver:
        descriptors.extend(map(int, jobserver.groups()))
    valid = []
    for fd in descriptors:
        try:
            os.fstat(fd)
            valid.append(fd)
        except OSError:
            pass
    return tuple(set(valid))


def build_lock(root):
    """Keep root links stable for a whole build, including recursive SDK makes."""
    lock_path = root / "output/.build.lock"
    lock_path.parent.mkdir(exist_ok=True)
    inherited = os.environ.get("SDK_BUILD_LOCK_FD")
    if inherited:
        try:
            fd = int(inherited)
            if os.path.samestat(os.fstat(fd), lock_path.stat()):
                return fd, False
        except (OSError, ValueError):
            pass
    fd = os.open(lock_path, os.O_CREAT | os.O_RDWR, 0o666)
    try:
        fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except BlockingIOError:
        os.close(fd)
        raise ValueError("Another SDK build is using the root configuration links; wait for it to finish")
    os.set_inheritable(fd, True)
    return fd, True


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--output", default="")
    parser.add_argument("--make", default="make")
    parser.add_argument("goals", nargs=argparse.REMAINDER)
    args = parser.parse_args()
    root = args.root.resolve()
    goals = args.goals[1:] if args.goals[:1] == ["--"] else args.goals
    output = resolve_output(root, args.output, goals)
    command = shlex.split(args.make) + ["--no-print-directory", "-C", str(root)]
    mode = make_inspection_mode()
    if mode:
        if mode == "dry-run":
            print("Would use SDK output: {}".format(output or "unconfigured"))
            print(shlex.join(command + goals))
        return 1 if mode == "question" else 0

    env = os.environ.copy()
    env.pop("CONFIG_SDK_ENABLE_CANMV", None)
    env.pop("MK_LIST_DEFCONFIG", None)
    env["SDK_BUILD_DISPATCHED"] = "1"
    if output:
        env["SDK_BUILD_DIR"] = str(output)
        env["SDK_CONFIG_FILE"] = str(output / ".config")

    def run_make(targets):
        return subprocess.call(command + targets, env=env, close_fds=False)

    if goals and set(goals) <= INSPECT_GOALS:
        # Inspect the requested output without migrating state, switching links,
        # or blocking another build. The selector may start its own locked make.
        if not output or not (output / ".config").is_file():
            env["SDK_CONFIG_FILE"] = str(root / ".config")
        return run_make(goals)

    fd, owned = build_lock(root)
    try:
        env["SDK_BUILD_LOCK_FD"] = str(fd)
        migrate_legacy(root)
        if output:
            output.mkdir(parents=True, exist_ok=True)
            (output / "include").mkdir(exist_ok=True)
            write_makefile(root, output)
        if goals and goals[0].endswith("_defconfig"):
            with config_transaction(output) as commit:
                status = run_make(goals)
                if status:
                    return status
                if config_name(output / ".config") != goals[0]:
                    raise ValueError("Generated configuration does not match {}".format(goals[0]))
                status = run_make([".autoconf"])
                if status:
                    return status
                activate_output(root, output)
                commit()
            return 0
        if output:
            activate_output(root, output)
        if output and needs_sync(goals):
            for target in ("sdk-kconfig", ".autoconf"):
                status = run_make([target])
                if status:
                    return status
            if goals == [".autoconf"]:
                return 0
        # Re-read the now synchronized .config before make evaluates conditionals.
        return run_make(goals)
    finally:
        if owned:
            os.close(fd)


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (OSError, ValueError) as error:
        sys.exit("SDK output: {}".format(error))
